<?php

declare(strict_types=1);

namespace App\Support;

/**
 * Concatenates the source stylesheets into the two bundles the layout loads.
 *
 * Source files stay in public/css so they remain editable; the bundles are
 * generated with `php artisan emplowise:bundle-css` and checked in, because the
 * static export ships public/ as-is and the app has no Node build step.
 */
final class CssBundles
{
    /** @var array<string, list<string>> */
    public const MANIFESTS = [
        'site.css' => [
            'fonts.css',
            'tokens.css',
            'base.css',
            'layout.css',
            'components.css',
            'pages.css',
            'intro.css',
            'consent.css',
            'theme.css',
            'chat.css',
            'inline.css',
        ],
        'hub.css' => [
            'student.css',
            'print.css',
        ],
    ];

    /**
     * @return array<string, string> bundle filename => generated contents
     */
    public static function build(): array
    {
        $bundles = [];

        foreach (self::MANIFESTS as $name => $sources) {
            $css = '';
            foreach ($sources as $source) {
                $css .= '/* '.$source.' */'."\n".self::minify(self::read($source))."\n";
            }
            $bundles[$name] = self::banner($name, $sources).$css;
        }

        return $bundles;
    }

    /**
     * @param  list<string>  $sources
     */
    public static function banner(string $name, array $sources): string
    {
        return '/*! '.$name.' — generated by `php artisan emplowise:bundle-css`.'
            .' Edit the sources in public/css, then regenerate. Sources: '
            .implode(', ', $sources).". */\n";
    }

    private static function read(string $source): string
    {
        return (string) file_get_contents(public_path('css/'.$source));
    }

    /**
     * Conservative minifier: strips comments and redundant whitespace while
     * leaving quoted strings, calc() spacing and media features untouched.
     */
    public static function minify(string $css): string
    {
        $css = (string) preg_replace('#/\*(?!!).*?\*/#s', '', $css);

        $parts = preg_split(
            '#("(?:[^"\\\\]|\\\\.)*"|\'(?:[^\'\\\\]|\\\\.)*\')#s',
            $css,
            -1,
            PREG_SPLIT_DELIM_CAPTURE
        );

        if ($parts === false) {
            return trim($css);
        }

        foreach ($parts as $index => $part) {
            if ($index % 2 === 1) {
                continue; // quoted string, keep verbatim
            }

            $part = (string) preg_replace('/\s+/', ' ', $part);
            $part = (string) preg_replace('/\s*([{};,])\s*/', '$1', $part);
            $parts[$index] = str_replace(';}', '}', $part);
        }

        return trim(implode('', $parts));
    }
}
